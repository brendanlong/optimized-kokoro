"""Writes src/unicode_tables.rs: the character classes and case/NFKC coverage misaki relies on, as the reference
Python sees them (Rust's own tables follow a newer Unicode version).

Run with the reference venv (reference/.cache/kfa/.venv/bin/python -I), which pins Python's unicodedata
(for str.isalpha) and the `regex` module (for \\p{L}, \\p{Lu}, \\p{Ll} and \\d in subtokenize).
"""

import os
import sys
import unicodedata

import regex

CHARS = [chr(c) for c in range(0x110000)]


def ranges(pred):
    out, start = [], None
    for c in range(0x110000):
        if pred(CHARS[c]):
            if start is None:
                start = c
        elif start is not None:
            out.append((start, c - 1))
            start = None
    if start is not None:
        out.append((start, 0x10FFFF))
    return out


def table(name, rs):
    body = "".join(f"    (0x{a:X}, 0x{b:X}),\n" for a, b in rs)
    return f"pub(crate) const {name}: &[(u32, u32)] = &[\n{body}];\n\n"


def main(dst):
    lu, ll, l, d = (regex.compile(p) for p in (r"\p{Lu}", r"\p{Ll}", r"\p{L}", r"\d"))
    src = (
        "// Generated by tools/gen_unicode.py with Python "
        f"{sys.version.split()[0]} (Unicode {unicodedata.unidata_version}) and regex {regex.__version__}. Do not edit.\n\n"
        + table("PY_ALPHA", ranges(str.isalpha))
        + table("PY_ASSIGNED", ranges(lambda c: unicodedata.category(c) != "Cn"))
        + table("PY_LOWER_CHANGES", ranges(lambda c: c.lower() != c))
        + table("PY_UPPER_CHANGES", ranges(lambda c: c.upper() != c))
        + table("RE_L", ranges(lambda c: l.match(c) is not None))
        + table("RE_LU", ranges(lambda c: lu.match(c) is not None))
        + table("RE_LL", ranges(lambda c: ll.match(c) is not None))
        + table("RE_DIGIT", ranges(lambda c: d.match(c) is not None))
    )
    with open(dst, "w") as f:
        f.write(src)


if __name__ == "__main__":
    main(sys.argv[1] if len(sys.argv) > 1 else os.path.join(os.path.dirname(__file__), "..", "src", "unicode_tables.rs"))
