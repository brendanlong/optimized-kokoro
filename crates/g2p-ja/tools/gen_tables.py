"""Writes src/tables.rs: misaki's cutlet tables and the Python character classes the port needs.

Run with the reference venv's Python (misaki 0.9.4, jaconv, Python 3.12's Unicode 15.0):
    ../../reference/.cache/kfa/.venv/bin/python -I tools/gen_tables.py src/tables.rs
"""

import sys
import unicodedata

from jaconv.conv_table import K2H_TABLE
from misaki import cutlet


def rs(s):
    return '"' + ''.join(c if c not in '"\\' else '\\' + c for c in s) + '"'


def ranges(pred):
    out, start = [], None
    for cp in range(0x110000 + 1):
        ok = cp < 0x110000 and not (0xD800 <= cp < 0xE000) and pred(chr(cp))
        if ok and start is None:
            start = cp
        elif not ok and start is not None:
            out.append((start, cp - 1))
            start = None
    return out


def main(path):
    lines = [
        "// Generated by tools/gen_tables.py from misaki 0.9.4's cutlet.py, jaconv and Python",
        f"// {sys.version.split()[0]} (Unicode {unicodedata.unidata_version}). Do not edit.",
        "",
        "/// cutlet's `HEPBURN` table (kana, digraphs and symbols to phonemes), sorted by key.",
        "pub static HEPBURN: &[(&str, &str)] = &[",
    ]
    for k, v in sorted(cutlet.HEPBURN.items()):
        lines.append(f"    ({rs(k)}, {rs(v)}),")
    lines += ["];", "", "/// `jaconv.kata2hira`'s table, sorted.", "pub static KATA2HIRA: &[(char, char)] = &["]
    for k, v in sorted(K2H_TABLE.items()):
        if chr(k) != v:
            lines.append(f"    ('{chr(k)}', '{v}'),")
    lines += ["];", ""]
    # str.isdigit(): runs of characters with consecutive digit values.
    runs = []
    for cp in range(0x110000):
        c = chr(cp)
        if 0xD800 <= cp < 0xE000 or not c.isdigit():
            continue
        d = unicodedata.digit(c)
        if runs and runs[-1][1] == cp - 1 and runs[-1][2] + (cp - runs[-1][0]) == d:
            runs[-1][1] = cp
        else:
            runs.append([cp, cp, d])
    lines += [
        "/// `str.isdigit()`: `(first, last, value of first)`, values rising by one.",
        "pub static DIGITS: &[(u32, u32, u8)] = &[",
    ]
    lines += [f"    (0x{a:x}, 0x{b:x}, {d})," for a, b, d in runs]
    lines += ["];", ""]
    lines += ["/// `str.isdecimal()` (Python `re`'s `\\d`).", "pub static DECIMALS: &[(u32, u32)] = &["]
    lines += [f"    (0x{a:x}, 0x{b:x})," for a, b in ranges(str.isdecimal)]
    lines += ["];", ""]
    with open(path, "w") as f:
        f.write("\n".join(lines))


if __name__ == "__main__":
    main(sys.argv[1])
