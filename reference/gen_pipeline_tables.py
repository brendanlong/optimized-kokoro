"""Writes crates/pipeline/src/tables.rs: the Unicode classes the English pipelines' foreign-script
splitting matches with the `regex` module (\\p{Script} for every script, \\p{Mn}, \\p{Cf}),
generated from the reference interpreter so the port uses the same Unicode version.

The scripts kokoro's foreign.py names (Han, Hiragana, Katakana, Latin, Arabic, Cyrillic,
Devanagari, Greek, Hangul, Hebrew) are matched as it writes them, `\\p{Han}`; the rest as
`\\p{Script=...}`. Script names are Unicode's (PropertyValueAliases.txt); any this `regex` doesn't
know yet are skipped.

Usage (from reference/, after ./setup.sh):
    .cache/kfa/.venv/bin/python -I gen_pipeline_tables.py ../crates/pipeline/src/tables.rs
"""

import sys

import regex

FOREIGN_PY = ["Han", "Hiragana", "Katakana", "Latin", "Arabic", "Cyrillic", "Devanagari", "Greek", "Hangul", "Hebrew"]
UNICODE_SCRIPTS = """
    Adlam Ahom Anatolian_Hieroglyphs Arabic Armenian Avestan Balinese Bamum Bassa_Vah Batak Bengali
    Beria_Erfe Bhaiksuki Bopomofo Brahmi Braille Buginese Buhid Canadian_Aboriginal Carian
    Caucasian_Albanian Chakma Cham Cherokee Chorasmian Coptic Cuneiform Cypriot Cypro_Minoan Cyrillic
    Deseret Devanagari Dives_Akuru Dogra Duployan Egyptian_Hieroglyphs Elbasan Elymaic Ethiopic Garay
    Georgian Glagolitic Gothic Grantha Greek Gujarati Gunjala_Gondi Gurmukhi Gurung_Khema Han Hangul
    Hanifi_Rohingya Hanunoo Hatran Hebrew Hiragana Imperial_Aramaic Inscriptional_Pahlavi
    Inscriptional_Parthian Javanese Jurchen Kaithi Kannada Katakana Kawi Kayah_Li Kharoshthi
    Khitan_Small_Script Khmer Khojki Khudawadi Kirat_Rai Lao Latin Lepcha Limbu Linear_A Linear_B Lisu
    Lycian Lydian Mahajani Makasar Malayalam Mandaic Manichaean Marchen Masaram_Gondi Medefaidrin
    Meetei_Mayek Mende_Kikakui Meroitic_Cursive Meroitic_Hieroglyphs Miao Modi Mongolian Mro Multani
    Myanmar Nabataean Nag_Mundari Nandinagari New_Tai_Lue Newa Nko Nushu Nyiakeng_Puachue_Hmong Ogham
    Ol_Chiki Ol_Onal Old_Hungarian Old_Italic Old_North_Arabian Old_Permic Old_Persian Old_Sogdian
    Old_South_Arabian Old_Turkic Old_Uyghur Oriya Osage Osmanya Pahawh_Hmong Palmyrene Pau_Cin_Hau
    Phags_Pa Phoenician Proto_Cuneiform Psalter_Pahlavi Rejang Runic Samaritan Saurashtra Seal Sharada
    Shavian Siddham Sidetic SignWriting Sinhala Sogdian Sora_Sompeng Soyombo Sundanese Sunuwar
    Syloti_Nagri Syriac Tagalog Tagbanwa Tai_Le Tai_Tham Tai_Viet Tai_Yo Takri Tamil Tangsa Tangut
    Telugu Thaana Thai Tibetan Tifinagh Tirhuta Todhri Tolong_Siki Toto Tulu_Tigalari Ugaritic Vai
    Vithkuqi Wancho Warang_Citi Yezidi Yi Zanabazar_Square
""".split()
CHARS = [chr(c) for c in range(0x110000) if not 0xD800 <= c < 0xE000]
TEXT = "".join(CHARS)


def ranges(pattern):
    out = []
    for m in regex.finditer(f"(?:{pattern})+", TEXT):
        for c in m.group():
            cp = ord(c)
            if out and out[-1][1] == cp - 1:
                out[-1][1] = cp
            else:
                out.append([cp, cp])
    return out


def script_pattern(name):
    return rf"\p{{{name}}}" if name in FOREIGN_PY else rf"\p{{Script={name}}}"


def u(cp):
    return f"'\\u{{{cp:x}}}'"


def main(dst):
    scripts = []
    known = []
    for name in UNICODE_SCRIPTS:
        try:
            found = ranges(script_pattern(name))
        except regex.error:
            continue
        if found:
            known.append(name)
            scripts.extend((a, b, name.replace("_", "")) for a, b in found)
    assert set(FOREIGN_PY) <= set(known)
    scripts.sort()
    for (_, end, x), (start, _, y) in zip(scripts, scripts[1:]):
        assert end < start, (x, y)
    marks = ranges(r"\p{Mn}")
    out = [
        f"// @generated by reference/gen_pipeline_tables.py from Python regex {regex.__version__}. Do not edit.\n",
        "// Derived from the Unicode Character Database; see COPYING.UCD.\n\n",
        "/// A Unicode script, other than Common, Inherited and Unknown.\n",
        "#[derive(Debug, Clone, Copy, PartialEq, Eq, Hash)]\n",
        "pub enum Script {\n",
    ]
    out += [f"    {name.replace('_', '')},\n" for name in known]
    out += [
        "}\n\n",
        "impl Script {\n",
        f"    pub const COUNT: usize = {len(known)};\n\n",
        "    /// Unicode's English name for the script.\n",
        "    pub fn name(self) -> &'static str {\n",
        "        match self {\n",
    ]
    out += [f'            Script::{name.replace("_", "")} => "{name.replace("_", " ")}",\n' for name in known]
    out += [
        "        }\n",
        "    }\n",
        "}\n\n",
        "/// `\\p{Script}`, as sorted, disjoint ranges.\n",
        "pub const SCRIPTS: &[(char, char, Script)] = &[\n",
    ]
    out += [f"    ({u(a)}, {u(b)}, Script::{name}),\n" for a, b, name in scripts]
    out += ["];\n\n", "/// `\\p{Mn}`.\n", "pub const NONSPACING_MARKS: &[(char, char)] = &[\n"]
    out += [f"    ({u(a)}, {u(b)}),\n" for a, b in marks]
    out += ["];\n\n", "/// `\\p{Cf}`.\n", "pub const FORMAT_CHARS: &[(char, char)] = &[\n"]
    out += [f"    ({u(a)}, {u(b)}),\n" for a, b in ranges(r"\p{Cf}")]
    out += ["];\n"]
    with open(dst, "w") as f:
        f.write("".join(out))


if __name__ == "__main__":
    main(sys.argv[1])
