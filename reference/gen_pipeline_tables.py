"""Writes crates/pipeline/src/tables.rs: the Unicode classes kokoro's foreign.py matches with the
`regex` module (\\p{Han}, \\p{Latin}, ..., \\p{Mn}), generated from the reference interpreter so
the port uses the same Unicode version.

Usage (from reference/, after ./setup.sh):
    .cache/kfa/.venv/bin/python -I gen_pipeline_tables.py ../crates/pipeline/src/tables.rs
"""

import sys

import regex

SCRIPTS = ["Han", "Hiragana", "Katakana", "Latin", "Arabic", "Cyrillic", "Devanagari", "Greek", "Hangul", "Hebrew"]
CHARS = [chr(c) for c in range(0x110000) if not 0xD800 <= c < 0xE000]


def ranges(pattern):
    compiled = regex.compile(pattern)
    out = []
    for c in CHARS:
        if compiled.fullmatch(c):
            cp = ord(c)
            if out and out[-1][1] == cp - 1:
                out[-1][1] = cp
            else:
                out.append([cp, cp])
    return out


def main(dst):
    scripts = []
    for name in SCRIPTS:
        scripts.extend((a, b, name) for a, b in ranges(rf"\p{{{name}}}"))
    scripts.sort()
    for (_, end, x), (start, _, y) in zip(scripts, scripts[1:]):
        assert end < start, (x, y)
    marks = ranges(r"\p{Mn}")
    out = [
        f"// @generated by reference/gen_pipeline_tables.py from Python regex {regex.__version__}. Do not edit.\n",
        "// Derived from the Unicode Character Database; see COPYING.UCD.\n\n",
        "use crate::foreign::Script;\n\n",
        "/// `\\p{Script}` for the scripts foreign.py names, as sorted, disjoint ranges.\n",
        "pub const SCRIPTS: &[(char, char, Script)] = &[\n",
    ]
    out += [f"    ('\\u{{{a:x}}}', '\\u{{{b:x}}}', Script::{name}),\n" for a, b, name in scripts]
    out += ["];\n\n", "/// `\\p{Mn}`.\n", "pub const NONSPACING_MARKS: &[(char, char)] = &[\n"]
    out += [f"    ('\\u{{{a:x}}}', '\\u{{{b:x}}}'),\n" for a, b in marks]
    out += ["];\n"]
    with open(dst, "w") as f:
        f.write("".join(out))


if __name__ == "__main__":
    main(sys.argv[1])
