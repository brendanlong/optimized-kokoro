"""Writes crates/text/src/tables.rs: the character classes the reference server's regexes use.

Python's `re` defines \\w, \\d and \\s by str.isalnum/isdecimal/isspace in its own Unicode version,
and the `regex` module has its own emoji properties; Rust's regex crate differs in both. Generating
the sets from the reference interpreter makes the port match it exactly.

Usage (from reference/, after ./setup.sh):
    .cache/kfa/.venv/bin/python -I gen_text_tables.py ../crates/text/src/tables.rs
"""

import re
import sys
import unicodedata

import regex

CHARS = [chr(c) for c in range(0x110000) if not 0xD800 <= c < 0xE000]


def ranges(pattern, module=re):
    compiled = module.compile(pattern)
    out = []
    for c in CHARS:
        if compiled.fullmatch(c):
            cp = ord(c)
            if out and out[-1][1] == cp - 1:
                out[-1][1] = cp
            else:
                out.append([cp, cp])
    return out


def table(name, rs, doc):
    body = "".join(f"    ('\\u{{{a:x}}}', '\\u{{{b:x}}}'),\n" for a, b in rs)
    return f"/// {doc}\npub const {name}: &[(char, char)] = &[\n{body}];\n"


def main(dst):
    parts = [
        "// @generated by reference/gen_text_tables.py from Python "
        f"{sys.version.split()[0]} (Unicode {unicodedata.unidata_version}) and regex {regex.__version__}.\n",
        table("WORD", ranges(r"\w"), "Python `re` `\\w`: `str.isalnum()` or `_`."),
        table("DIGIT", ranges(r"\d"), "Python `re` `\\d`: `str.isdecimal()`. Every range is whole blocks of ten, 0 to 9."),
        table("SPACE", ranges(r"\s"), "Python `re` `\\s`: `str.isspace()`, also what `str.strip()` removes."),
        table(
            "EMOJI_START",
            ranges(r"[\p{Extended_Pictographic}\p{Regional_Indicator}]", regex),
            "`regex` `[\\p{Extended_Pictographic}\\p{Regional_Indicator}]`.",
        ),
        table("EMOJI_MODIFIER", ranges(r"\p{Emoji_Modifier}", regex), "`regex` `\\p{Emoji_Modifier}`."),
    ]
    with open(dst, "w") as f:
        f.write("\n".join(parts))


if __name__ == "__main__":
    main(sys.argv[1])
