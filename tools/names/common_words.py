"""Lists the names that are also common words in the languages espeak reads Latin text in, as
candidates for exclude_languages.tsv (names a pipeline doesn't read as names).

    uv run --with wordfreq==3.1.1 tools/names/common_words.py > tools/names/review/common_words.tsv

A candidate is a single-word name whose lowercase form is used at least once per hundred million words
(zipf >= 2) in wordfreq's list for the language. wordfreq counts names too, so Tolkien's best-known
names (Mordor, Sauron) are candidates for their own fame; exclude_languages.tsv is the reviewed list.
"""

import json
from pathlib import Path

from wordfreq import zipf_frequency

ROOT = Path(__file__).resolve().parents[2]
LANGUAGES = ["es", "fr", "it", "pt"]
ZIPF = 2.0


def main():
    names = json.load(open(ROOT / "crates/g2p-en/data/names.json", encoding="utf-8"))
    print("# language\tspelling\tzipf (generated by common_words.py)")
    for lang in LANGUAGES:
        found = sorted(((zipf_frequency(n.lower(), lang), n) for n, p in names.items() if p and " " not in n and "-" not in n), reverse=True)
        for zipf, name in found:
            if zipf >= ZIPF:
                print(f"{lang}\t{name}\t{zipf:.2f}")


if __name__ == "__main__":
    main()
