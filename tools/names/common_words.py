"""Lists the names that are also common words in the languages espeak reads Latin text in, as
candidates for exclude_languages.tsv (names a pipeline doesn't read as names).

    uv run --with wordfreq==3.1.1 tools/names/common_words.py > tools/names/review/common_words.tsv

A candidate is a word used at least once per hundred million words (zipf >= 2) in wordfreq's list for
the language that the G2P would read as a name: in any case, with some of the name's accents left out
and none added (crates/g2p-en/src/names.rs). wordfreq counts words whatever their case, so Tolkien's
best-known names (Mordor, Sauron) are candidates for their own fame; exclude_languages.tsv is the
reviewed list.
"""

import json
import unicodedata
from pathlib import Path

from wordfreq import iter_wordlist, zipf_frequency

ROOT = Path(__file__).resolve().parents[2]
LANGUAGES = ["es", "fr", "it", "pt"]
ZIPF = 2.0


def clusters(s):
    """Each letter, lowercase, with its accents."""
    out = []
    for c in unicodedata.normalize("NFD", s):
        if unicodedata.category(c).startswith("M") and out:
            out[-1][1].append(c)
        else:
            out.append([c.lower(), []])
    return out


def fold(s):
    return "".join(letter for letter, _ in clusters(s))


def accents_within(word, name):
    a, b = clusters(word), clusters(name)
    return len(a) == len(b) and all(x[0] == y[0] and (not x[1] or x[1] == y[1]) for x, y in zip(a, b))


def main():
    names = json.load(open(ROOT / "crates/g2p-en/data/names.json", encoding="utf-8"))
    by_key = {}
    for name, phonemes in names.items():
        if " " not in name and "-" not in name:
            by_key.setdefault(fold(name), []).append((name, phonemes))
    print("# language\tword\tname\tzipf (generated by common_words.py)")
    for lang in LANGUAGES:
        for word in iter_wordlist(lang):
            zipf = zipf_frequency(word, lang)
            if zipf < ZIPF:
                break
            found = [(n, p) for n, p in by_key.get(fold(word), []) if accents_within(word, n)]
            if found and len({p for _, p in found}) == 1 and found[0][1]:
                print(f"{lang}\t{word}\t{found[0][0]}\t{zipf:.2f}")


if __name__ == "__main__":
    main()
